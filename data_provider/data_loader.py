class Dataset_PEMS(Dataset):
    """
    Dataset class for PEMS03/04/07/08 traffic datasets stored in .npz format.
    Expected .npz structure: data with shape (T, N, C), where
        T = timesteps, N = number of nodes/sensors, C = 3 channels (flow, occupancy, speed).
    Uses the first channel (flow) for forecasting by default.
    Splits data into 60% train, 20% validation, 20% test.
    """
    def __init__(self, root_path, flag='train', size=None,
                 features='M', data_path='PEMS08.npz',
                 target='OT', scale=True, timeenc=0, freq='h', seasonal_patterns=None):
        # size [seq_len, label_len, pred_len]
        if size == None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        # init
        assert flag in ['train', 'test', 'val']
        type_map = {'train': 0, 'val': 1, 'test': 2}
        self.set_type = type_map[flag]

        self.features = features
        self.target = target
        self.scale = scale
        self.timeenc = timeenc
        self.freq = freq

        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = StandardScaler()
        # Load .npz file: expected shape (T, N, C) with C=3 (flow, occupy, speed)
        data_raw = np.load(os.path.join(self.root_path, self.data_path))
        if isinstance(data_raw, np.lib.npyio.NpzFile):
            # Use the first array key (typically 'data')
            key = list(data_raw.keys())[0]
            data_raw = data_raw[key]
        # data_raw shape: (T, N, C) 鈥?take first channel (flow)
        if data_raw.ndim == 3:
            data_raw = data_raw[:, :, 0]   # (T, N) 鈥?select flow channel

        # Split: 60% train, 20% val, 20% test
        num_train = int(len(data_raw) * 0.6)
        num_test = int(len(data_raw) * 0.2)
        num_vali = len(data_raw) - num_train - num_test
        border1s = [0, num_train - self.seq_len, num_train + num_vali - self.seq_len]
        border2s = [num_train, num_train + num_vali, num_train + num_vali + num_test]
        border1 = border1s[self.set_type]
        border2 = border2s[self.set_type]

        df_data = pd.DataFrame(data_raw)

        if self.features == 'M' or self.features == 'MS':
            cols_data = df_data.columns
            df_data = df_data[cols_data]
        elif self.features == 'S':
            df_data = df_data[[int(self.target)] if self.target.lstrip('-').isdigit() else df_data.columns[0:1]]

        if self.scale:
            train_data = df_data.values[border1s[0]:border2s[0]]
            self.scaler.fit(train_data)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values

        # Generate synthetic timestamps: 5-min interval starting from a reference date
        # PEMS08 starts ~2016-07-01, PEMS03/04/07 start ~2012-05-01
        total_len = len(data_raw)
        if 'PEMS08' in self.data_path or 'PEMS08' in self.root_path:
            start_date = '2016-07-01'
        else:
            start_date = '2012-05-01'
        dates = pd.date_range(start=start_date, periods=total_len, freq='5min')
        df_stamp = pd.DataFrame({'date': dates[border1:border2]})

        if self.timeenc == 0:
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            df_stamp['minute'] = df_stamp.date.apply(lambda row: row.minute, 1)
            data_stamp = df_stamp.drop(['date'], 1).values
        elif self.timeenc == 1:
            data_stamp = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = data_stamp.transpose(1, 0)

        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]
        self.data_stamp = data_stamp

    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        seq_y = self.data_y[r_begin:r_end]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]

        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.data_x) - self.seq_len - self.pred_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)


